"""Synthetic and released-byte upgrade checks; no application data or network."""
import hashlib
import importlib.util
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest
from unittest.mock import patch


ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location('skill_upgrade_installer', ROOT / 'tools/install.py')
installer = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(installer)


class UpgradeTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.base = Path(self.temp.name).resolve()
        self.source = self.base / 'source'
        self.source.mkdir()
        (self.source / 'SKILL.md').write_bytes(b'old skill\n')
        (self.source / 'scripts').mkdir()
        (self.source / 'scripts/reader.py').write_bytes(b'old reader\n')
        self.project = self.base / 'project'
        self.project.mkdir()
        self.target = Path(installer.install(self.source, self.project, 'codex', True)['target'])
        self.old = installer.manifest(self.target)
        self.release = {'v-test': {'manifest': self.old, 'manifest_sha256': installer.manifest_sha(self.old)}}
        (self.source / 'SKILL.md').write_bytes(b'new skill\n')
        (self.source / 'scripts/reader.py').write_bytes(b'new reader\n')
        self.patcher = patch.object(installer, 'known_releases', return_value=self.release)
        self.patcher.start()
        self.addCleanup(self.patcher.stop)

    def run_upgrade(self, apply=True):
        return installer.upgrade(self.source, self.project, 'codex', apply)

    def test_preview_is_read_only_and_upgrade_keeps_exact_backup(self):
        cache = self.target / 'scripts/__pycache__'
        cache.mkdir()
        (cache / 'old.pyc').write_bytes(b'generated bytes retained in backup')
        before = sorted(str(p.relative_to(self.project)) for p in self.project.rglob('*'))
        self.assertEqual(self.run_upgrade(False)['status'], 'READY_UPGRADE')
        self.assertEqual(sorted(str(p.relative_to(self.project)) for p in self.project.rglob('*')), before)
        result = self.run_upgrade()
        self.assertEqual(result['status'], 'UPGRADED')
        self.assertEqual(installer.manifest(self.target), installer.manifest(self.source))
        backup = Path(result['backup'])
        self.assertEqual(installer.manifest(backup), self.old)
        self.assertEqual((backup / 'scripts/__pycache__/old.pyc').read_bytes(), b'generated bytes retained in backup')
        self.assertFalse((self.target / 'scripts/__pycache__').exists())
        self.assertEqual(result['previous_manifest_sha256'], installer.manifest_sha(self.old))

    def test_repeat_upgrade_is_unchanged_with_no_second_backup(self):
        first = self.run_upgrade()
        before = sorted(str(p) for p in self.project.rglob('*'))
        self.assertEqual(self.run_upgrade()['status'], 'UNCHANGED')
        self.assertEqual(sorted(str(p) for p in self.project.rglob('*')), before)
        self.assertTrue(Path(first['backup']).is_dir())

    def test_modified_unknown_and_extra_directory_preserved(self):
        for kind in ('modified', 'extra', 'empty-directory'):
            with self.subTest(kind=kind):
                change = self.target / ('SKILL.md' if kind == 'modified' else kind)
                if kind == 'empty-directory':
                    change.mkdir()
                else:
                    change.write_text('user owned')
                with self.assertRaisesRegex(installer.InstallError, 'modified or not a known release'):
                    self.run_upgrade()
                self.assertTrue(change.exists())
                if kind == 'modified':
                    self.assertEqual(change.read_text(), 'user owned')
                    change.write_bytes(b'old skill\n')
                elif kind == 'empty-directory':
                    change.rmdir()
                else:
                    change.unlink()

    def test_unknown_release_does_not_upgrade(self):
        self.release.clear()
        with self.assertRaises(installer.InstallError):
            self.run_upgrade()
        self.assertEqual(installer.manifest(self.target), self.old)

    def test_missing_target_requires_install(self):
        empty = self.base / 'empty-project'
        empty.mkdir()
        with self.assertRaisesRegex(installer.InstallError, 'use --install'):
            installer.upgrade(self.source, empty, 'codex', True)
        self.assertEqual(list(empty.iterdir()), [])

    def test_lock_blocks_both_mutations_without_removing_owner_lock(self):
        with installer.installation_lock(self.project, 'codex'):
            lock = self.project / '.kakaotalk-mac-codex-install.lock'
            for operation in (lambda: self.run_upgrade(),
                              lambda: installer.install(self.source, self.project, 'codex', True)):
                with self.assertRaisesRegex(installer.InstallError, 'locked'):
                    operation()
                self.assertTrue(lock.is_file())
        self.assertFalse(lock.exists())

    def test_source_change_before_publication_preserves_old_target(self):
        real_copy = installer.copy_file
        def change(source, target, digest, created):
            real_copy(source, target, digest, created)
            if source.name == 'SKILL.md':
                (self.source / 'scripts/reader.py').write_bytes(b'concurrent source edit')
        with patch.object(installer, 'copy_file', side_effect=change):
            with self.assertRaises(installer.InstallError):
                self.run_upgrade()
        self.assertEqual(installer.manifest(self.target), self.old)
        self.assertEqual(list(self.target.parent.glob('*.stage-*')), [])

    def test_target_change_before_switch_preserves_user_edit(self):
        real_copy = installer.copy_file
        def change(*args):
            real_copy(*args)
            (self.target / 'SKILL.md').write_bytes(b'concurrent target edit')
        with patch.object(installer, 'copy_file', side_effect=change):
            with self.assertRaisesRegex(installer.InstallError, 'changed during upgrade'):
                self.run_upgrade()
        self.assertEqual((self.target / 'SKILL.md').read_bytes(), b'concurrent target edit')

    def test_publish_failure_restores_previous_installation(self):
        real_rename = installer.rename_exclusive
        def fail_publish(source, target):
            if '.stage-' in source.name:
                raise OSError('synthetic publication failure')
            return real_rename(source, target)
        with patch.object(installer, 'rename_exclusive', side_effect=fail_publish):
            with self.assertRaisesRegex(installer.InstallError, 'previous installation restored'):
                self.run_upgrade()
        self.assertEqual(installer.manifest(self.target), self.old)
        self.assertEqual([p.name for p in self.target.parent.iterdir()], ['kakaotalk-mac'])

    def test_concurrent_destination_is_never_replaced(self):
        real_rename = installer.rename_exclusive
        def create_destination(source, target):
            if '.stage-' in source.name:
                target.mkdir()
                (target / 'user.txt').write_text('do not remove')
            return real_rename(source, target)
        with patch.object(installer, 'rename_exclusive', side_effect=create_destination):
            with self.assertRaisesRegex(installer.InstallError, 'preserved at'):
                self.run_upgrade()
        self.assertEqual((self.target / 'user.txt').read_text(), 'do not remove')
        backups = list((self.project / '.kakaotalk-mac-backups/codex').glob('kakaotalk-mac-*'))
        self.assertEqual(len(backups), 1)
        self.assertEqual(installer.manifest(backups[0]), self.old)

    def test_even_empty_concurrent_destination_is_not_replaced(self):
        source = self.base / 'rename-source'
        target = self.base / 'rename-target'
        source.mkdir()
        target.mkdir()
        original = installer.identity(target)
        with self.assertRaises(OSError):
            installer.rename_exclusive(source, target)
        self.assertTrue(source.is_dir())
        self.assertEqual(installer.identity(target), original)

    def test_after_publish_edit_keeps_both_new_folder_and_backup(self):
        real_rename = installer.rename_exclusive
        def mutate_published(source, target):
            real_rename(source, target)
            if '.stage-' in source.name:
                (target / 'SKILL.md').write_text('concurrent published edit')
        with patch.object(installer, 'rename_exclusive', side_effect=mutate_published):
            with self.assertRaisesRegex(installer.InstallError, 'activated folder preserved'):
                self.run_upgrade()
        self.assertEqual((self.target / 'SKILL.md').read_text(), 'concurrent published edit')
        backups = list((self.project / '.kakaotalk-mac-backups/codex').glob('kakaotalk-mac-*'))
        self.assertEqual(installer.manifest(backups[0]), self.old)

    def test_links_inside_generated_cache_are_rejected(self):
        cache = self.target / '__pycache__'
        cache.mkdir()
        try:
            (cache / 'linked').symlink_to(self.source, target_is_directory=True)
        except OSError as exc:
            self.skipTest(str(exc))
        with self.assertRaisesRegex(installer.InstallError, 'links and reparse'):
            self.run_upgrade()
        self.assertEqual(installer.manifest(self.target), self.old)

    def test_root_home_traversal_and_source_overlap_still_rejected(self):
        for project in (Path.home(), Path(self.project.anchor), self.project / '..' / 'project'):
            with self.assertRaises(installer.InstallError):
                installer.upgrade(self.source, project, 'codex', True)
        with self.assertRaises(installer.InstallError):
            installer.upgrade(self.target, self.project, 'codex', True)

    def test_oversized_unknown_file_is_rejected_before_hashing(self):
        extra = self.target / 'extra.bin'
        with extra.open('wb') as stream:
            stream.truncate(1024 * 1024 + 1)
        with self.assertRaisesRegex(installer.InstallError, 'size limit'):
            self.run_upgrade()
        self.assertTrue(extra.exists())

    def test_oversized_source_is_rejected_before_read_bytes(self):
        extra = self.source / 'extra.bin'
        with extra.open('wb') as stream:
            stream.truncate(1024 * 1024 + 1)
        with patch.object(Path, 'read_bytes', side_effect=AssertionError('unbounded read attempted')):
            with self.assertRaisesRegex(installer.InstallError, 'size limit'):
                self.run_upgrade()
        self.assertEqual(installer.manifest(self.target), self.old)


class KnownReleaseTests(unittest.TestCase):
    def test_bundled_release_variants_are_self_consistent(self):
        releases = installer.known_releases()
        self.assertEqual(set(releases), {'v0.2.0', 'v0.2.0-crlf'})
        for record in releases.values():
            self.assertEqual(record['commit'], '5d887e4153f4bff9658246a0a47cae60e1112601')
            self.assertEqual(record['manifest_sha256'], installer.manifest_sha(record['manifest']))

    def test_exact_git_release_bytes_upgrade_for_lf_and_crlf(self):
        if not shutil.which('git') or not (ROOT / '.git').exists():
            self.skipTest('Released Git objects are not included in this source copy')
        check = subprocess.run(['git', 'cat-file', '-e', 'v0.2.0^{commit}'], cwd=ROOT, capture_output=True)
        if check.returncode:
            self.skipTest('v0.2.0 Git objects are not present in this checkout')
        releases = installer.known_releases()
        with tempfile.TemporaryDirectory() as temporary:
            base = Path(temporary).resolve()
            for label, record in releases.items():
                with self.subTest(label=label):
                    project = base / label
                    project.mkdir()
                    target = project / '.agents/skills/kakaotalk-mac'
                    target.mkdir(parents=True)
                    for name, digest in record['manifest'].items():
                        path = target / name.rstrip('/')
                        if digest is None:
                            path.mkdir(exist_ok=True)
                        else:
                            body = subprocess.check_output(['git', 'show', 'v0.2.0:skills/kakaotalk-mac/' + name], cwd=ROOT)
                            if label.endswith('-crlf'):
                                body = body.replace(b'\n', b'\r\n')
                            self.assertEqual(hashlib.sha256(body).hexdigest(), digest)
                            path.write_bytes(body)
                    result = installer.upgrade(ROOT / 'skills/kakaotalk-mac', project, 'codex', True)
                    self.assertEqual(result['status'], 'UPGRADED')
                    self.assertEqual(installer.manifest(Path(result['backup'])), record['manifest'])
                    self.assertEqual(installer.manifest(target), installer.manifest(ROOT / 'skills/kakaotalk-mac'))


if __name__ == '__main__':
    unittest.main()
